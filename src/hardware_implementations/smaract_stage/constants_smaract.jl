function Base.getproperty(x::SA_CTL_Event_t, f::Symbol)
    r = Ref{SA_CTL_Event_t}(x)
    ptr = Base.unsafe_convert(Ptr{SA_CTL_Event_t}, r)
    fptr = getproperty(ptr, f)
    GC.@preserve r unsafe_load(fptr)
